'''

Metadata management in a Lakehouse is process of storing, organizing, and managing information
about data, rather than the data itself.

This includes tables definitions, column types, partitions, ownership, lineage and version history



Efficient query performance

    Metadata helps query engines know where data is stored, which files to read, and how to
    interpret schema, reducing scan time


Data governance & security 

    Tracks ownership, access permissions, and data classification, enabling compliance and controlled
    access


Data lineage & auditing 

    Maintains a history of transformations and movement of data for debugging and regulatory
    reporting


Time travel / versioning support

    Stores historical snapshots of data for rollbakc or analysis of past states

'''